@dataclass(frozen=True)
class ActionClassification:
    role: str
    action_key: str | None
    lane: str | None
    spell_id: int | None


def _spell_parts(spell: Mapping[str, Any]) -> tuple[int | None, str | None]:
    raw_id = spell.get("id")
    spell_id = (
        raw_id
        if isinstance(raw_id, int) and not isinstance(raw_id, bool) and raw_id > 0
        else None
    )
    raw_name = spell.get("name")
    name = raw_name.strip().casefold() if isinstance(raw_name, str) and raw_name.strip() else None
    return spell_id, name


def _action_spec(spell: Mapping[str, Any]) -> ActionSpec | None:
    spell_id, name = _spell_parts(spell)
    if spell_id is not None:
        return _SPEC_BY_ID.get(spell_id)
    return _SPEC_BY_NAME.get(name) if name is not None else None


def classify_action_event(
    *, event_type: str, spell: Mapping[str, Any]
) -> ActionClassification:
    """Classify one Chronicle START/GO/FAIL without guessing from a GO name."""

    if event_type not in {"START", "GO", "FAIL"}:
        raise ValueError(f"unsupported action event type: {event_type}")
    spell_id, name = _spell_parts(spell)
    if spell_id in EXOGENOUS_SPELL_IDS or (
        spell_id is None and name in EXOGENOUS_NAMES
    ):
        return ActionClassification(ROLE_EXOGENOUS, None, None, spell_id)
    if spell_id in CONTROLLED_RESULT_SPELL_IDS:
        return ActionClassification(ROLE_CONTROLLED_OUTCOME, None, None, spell_id)

    spec = _action_spec(spell)
    if spec is None:
        role = ROLE_OUT_OF_ONTOLOGY if event_type in {"START", "FAIL"} else ROLE_UNRESOLVED_GO
        return ActionClassification(role, None, None, spell_id)
    if event_type == "FAIL":
        return ActionClassification(
            ROLE_FAILED_ATTEMPT, spec.action_key, spec.lane, spell_id
        )
    if event_type == "START":
        return ActionClassification(
            ROLE_CONTROLLABLE_START, spec.action_key, spec.lane, spell_id
        )
    if spec.unpaired_go_is_decision:
        return ActionClassification(
            ROLE_CONTROLLABLE_INSTANT_GO, spec.action_key, spec.lane, spell_id
        )
    return ActionClassification(
        ROLE_CONTROLLED_OUTCOME, spec.action_key, spec.lane, spell_id
    )


@dataclass(frozen=True)
class CharacterInventorySnapshot:
    instance_ref: str
    encounter_id: str
    player_guid: str
    event_index: int
    message_ordinal: int
    gear_slots: tuple[JSONMap, ...]
    talent_summary: tuple[int, ...] | None
    talent_trees: tuple[str, ...] | None

    def feature_profile(self) -> JSONMap:
        return {
            "gear_slots": [dict(slot) for slot in self.gear_slots],
            "talent_summary": (
                list(self.talent_summary) if self.talent_summary is not None else None
            ),
            "talent_trees": (
                list(self.talent_trees) if self.talent_trees is not None else None
            ),
        }


class CharacterInventoryIndex:
    """Small causal INFO index preserving slot/enchant/gem/talent fields."""

    def __init__(self, records: Iterable[Mapping[str, Any]]) -> None:
        grouped: dict[
            tuple[str, str, str], list[CharacterInventorySnapshot]
        ] = defaultdict(list)
        observed_encounters: set[tuple[str, str]] = set()
        observed_players: set[tuple[str, str, str]] = set()
        for record in records:
            if record.get("schema") != COMBATANT_RECORD_SCHEMA:
                raise ValueError(f"unsupported CombatantInfo row schema: {record.get('schema')!r}")
            instance_ref = str(record.get("instance_ref") or "")
            encounter_id = str(record.get("encounter_id") or "")
            player = record.get("player")
            if not instance_ref or not encounter_id or not isinstance(player, Mapping):
                raise ValueError("CombatantInfo row is missing instance/encounter/player")
            player_guid = str(player.get("guid") or "").strip().lower()
            if not player_guid:
                raise ValueError("CombatantInfo row is missing exact player GUID")
            key = (instance_ref, encounter_id, player_guid)
            observed_encounters.add((instance_ref, encounter_id))
            observed_players.add(key)
            anchor = record.get("anchor")
            if anchor is None:
                continue
            if not isinstance(anchor, Mapping):
                raise ValueError("CombatantInfo anchor must be an object")
            event_index = anchor.get("event_index")
            ordinal = record.get("message_ordinal")
            if (
                isinstance(event_index, bool)
                or not isinstance(event_index, int)
                or isinstance(ordinal, bool)
                or not isinstance(ordinal, int)
            ):
                raise ValueError("CombatantInfo event index/ordinal must be integers")
            grouped[key].append(
                CharacterInventorySnapshot(
                    instance_ref=instance_ref,
                    encounter_id=encounter_id,
                    player_guid=player_guid,
                    event_index=event_index,
                    message_ordinal=ordinal,
                    gear_slots=_gear_slots(record.get("gear")),
                    talent_summary=_talent_summary(record.get("talents")),
                    talent_trees=_talent_trees(record.get("talents")),
                )
            )
        self._observed_encounters = observed_encounters
        self._observed_players = observed_players
        self._rows: dict[
            tuple[str, str, str], tuple[tuple[tuple[int, int], ...], tuple[CharacterInventorySnapshot, ...]]
        ] = {}
        for key, values in grouped.items():
            ordered = tuple(sorted(values, key=lambda row: (row.event_index, row.message_ordinal)))
            self._rows[key] = (
                tuple((row.event_index, row.message_ordinal) for row in ordered),
                ordered,
            )

    def select(
        self,
        *,
        instance_ref: str,
        encounter_id: str,
        player_guid: str,
        event_index: int,
    ) -> tuple[CharacterInventorySnapshot | None, str]:
        key = (instance_ref, encounter_id, player_guid.strip().lower())
        if (instance_ref, encounter_id) not in self._observed_encounters:
            return None, "encounter_missing"
        if key not in self._observed_players:
            return None, "guid_mismatch"
        found = self._rows.get(key)
        if found is None:
            return None, "unanchored_info_only"
        anchors, rows = found
        position = bisect_right(anchors, (event_index, 2**63 - 1))
        if position == 0:
            return None, "late_info_only"
        return rows[position - 1], "matched"


def _gear_slots(raw: Any) -> tuple[JSONMap, ...]:
    if not isinstance(raw, list):
        return ()
    result: list[JSONMap] = []
    for slot in raw:
        if not isinstance(slot, Mapping):
            raise ValueError("CombatantInfo gear slot must be an object")
        slot_index = slot.get("slot_index")
        item_id = slot.get("item_id")
        if any(isinstance(value, bool) or not isinstance(value, int) for value in (slot_index, item_id)):
            raise ValueError("CombatantInfo slot_index/item_id must be integers")
        gems = slot.get("gem_enchant_ids", [])
        if not isinstance(gems, list) or any(isinstance(value, bool) or not isinstance(value, int) for value in gems):
            raise ValueError("CombatantInfo gem enchant IDs must be integers")
        result.append(
            {
                "slot_index": slot_index,
                "item_id": item_id,
                "enchant_id": slot.get("enchant_id"),
                "temporary_enchant_id": slot.get("temporary_enchant_id"),
                "gem_enchant_ids": list(gems),
            }
        )
    return tuple(sorted(result, key=lambda row: row["slot_index"]))


def _talent_summary(raw: Any) -> tuple[int, ...] | None:
    if not isinstance(raw, Mapping):
        return None
    values = raw.get("summary")
    if not isinstance(values, list) or any(isinstance(value, bool) or not isinstance(value, int) for value in values):
        return None
    return tuple(values)


def _talent_trees(raw: Any) -> tuple[str, ...] | None:
    if not isinstance(raw, Mapping):
        return None
    values = raw.get("trees")
    if not isinstance(values, list) or not all(isinstance(value, str) for value in values):
        return None
    return tuple(values)


def inventory_index_from_compressed_stream(
    compressed: bytes, *, instance_ref: str, slug: str
) -> CharacterInventoryIndex:
    """Decode one small official CombatantInfo object into a causal index."""

    frames = decode_combatant_info_stream(compressed)
    return CharacterInventoryIndex(
        sidecar_records(frames, instance_ref=instance_ref, slug=slug)
    )


